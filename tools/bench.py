"""Benchmark: measure how well a model (or person, or setup) matches functions, by re-solving functions already solved.

Used by `tools/cd2.py bench ...`:
  list [--tier N]                 every function that could be a task: exact functions a person writes (not
                                  compiler-generated), with their tier
  suite [--make]                  the benchmark suite (config/bench_suite.json): a fixed set of tasks, so that results
                                  stay comparable between models and over time; --make (maintainers) regenerates it
  prepare <address> --model M     a self-contained workspace <bench dir>/<M>/<address>: the source file with that one
                                  function's body blanked, a copy of include/ and the shared notes, and TASK.md
  check <address> --model M       score the workspace: the source policy, then exact (bytes and relocation targets)
                                  or the share of words; every check is counted as an attempt
  run --agent CMD --model M       the whole suite (or --tier/--limit) with any agent: for each task, prepare the
                                  workspace, run CMD in it (TASK.md on stdin, {task} and {workspace} in CMD replaced,
                                  CD2_TASK/CD2_WORKSPACE/CD2_CHECK set), then score it
  report                          results by model and tier
  selftest                        the harness itself, on every suite task: an oracle agent (it pastes the known
                                  solution) must reach EXACT; a do-nothing agent and three cheating agents must not

Against cheating:
- the workspaces live outside the repository (CD2_BENCH_DIR, local.json "bench_dir", else %LOCALAPPDATA%\\cd2-bench),
  so the solutions in src/ are not next to them, and no agent picks up the repository's instructions or git history;
- the results live beside the workspace, not in it, and the verdict is the final check after the agent exits, so a
  forged result file changes nothing;
- the source policy applies, with only the workspace and the XDK as allowed origins: no __emit of CD2's words, no
  #include of the repository's own file;
- `same_as_repository` flags a solution identical to the repository's (expected for tiny functions; suspicious for
  long ones).
An agent with an unrestricted shell can still look elsewhere on the machine: run agents sandboxed (`--agent
chat:<model>` is sandboxed by construction, tools/bench_chat.py; `claude:<model>` and `kilo:<provider/model>` confine
those CLIs), and never with web access, since the solutions are public.
"""
import collections, datetime, json, os, re, shutil, subprocess, sys, tempfile, time

TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, TOOLS)
import coff  # noqa: E402
import relocs  # noqa: E402
import search  # noqa: E402
from verify_src import ROOT, XDK, BIN, FLAGS, local_config, run_compiler  # noqa: E402

BENCH = os.path.abspath(os.environ.get('CD2_BENCH_DIR') or local_config().get('bench_dir')
                        or os.path.join(os.environ.get('LOCALAPPDATA') or tempfile.gettempdir(), 'cd2-bench'))
SUITE = os.path.join(ROOT, 'config', 'bench_suite.json')
PER_TIER = {1: 8, 2: 8, 3: 5, 4: 2}  # tasks per tier in the suite (the whole tier when it has fewer)
GENERATED = re.compile(r'^\?\?(_G|_E|_9|__E|__F|_7)|@W[A-Z0-9]+@')  # deleting dtors, thunks, initializers, adjustors


def candidates(manifest):
    """[(file, entry)] of exact, plain-build functions whose body a person writes in that file (not compiler-generated,
    not instantiated from a library header such as the STL's)."""
    out = []
    for f, entries in manifest['files'].items():
        text = open(os.path.join(ROOT, f), newline='').read()
        for e in entries:
            if not e.get('matching', True) or e.get('ltcg') or e.get('folded') or GENERATED.search(e['symbol']):
                continue
            try:
                search.find_body(text, e['symbol'])
            except ValueError:
                continue
            out.append((f, e))
    return out


def make_suite(tasks):
    """tasks: [dict(address, size, file, symbol, tier)]. Per tier, evenly spaced by size (deterministic)."""
    out = []
    for t, k in sorted(PER_TIER.items()):
        xs = sorted((x for x in tasks if x['tier'] == t), key=lambda x: (x['size'], x['address']))
        out += xs if len(xs) <= k else [xs[round(i * (len(xs) - 1) / (k - 1))] for i in range(k)]
    suite = dict(version=1, note='the benchmark suite: generated by `cd2.py bench suite --make`; keep it fixed so '
                                 'results stay comparable', tasks=out)
    json.dump(suite, open(SUITE, 'w', newline='\n'), indent=1)
    return suite


def load_suite():
    return json.load(open(SUITE)) if os.path.exists(SUITE) else None


def model_dir(model):
    return re.sub(r'[^\w.-]', '_', model or 'unnamed')


def workspace(addr, model):
    """The agent's directory."""
    return os.path.join(BENCH, model_dir(model), '%08X' % addr)


def result_path(addr, model):
    """The harness's record of a task: beside the workspace, not in it."""
    return os.path.join(BENCH, model_dir(model), 'results', '%08X.json' % addr)


def location_problem():
    """Why BENCH cannot hold workspaces, or None: inside the repository, an agent would sit next to the solutions."""
    root, b = os.path.normcase(ROOT), os.path.normcase(BENCH)
    try:
        inside = os.path.commonpath([root, b]) == root
    except ValueError:  # another drive
        inside = False
    return ('the benchmark directory %s is inside the repository; set CD2_BENCH_DIR (or "bench_dir" in local.json) '
            'to a directory outside it' % BENCH) if inside else None


def _arg(path):
    """A path as a command argument that works in cmd, PowerShell and bash alike."""
    path = path.replace('\\', '/')
    return '"%s"' % path if ' ' in path else path


def body_text(text, symbol):
    """The function's body with comments and whitespace removed, or None if it cannot be found."""
    try:
        s, e = search.find_body(text, symbol)
    except ValueError:
        return None
    body = re.sub(r'//[^\n]*|/\*.*?\*/', '', text[s:e], flags=re.S)
    return re.sub(r'\s+', '', body)


def prepare(file, entry, brief, model=None):
    """Create the workspace; returns its path. brief: dict from `cd2 show` (assembly, hints, tier, ...)."""
    addr = int(entry['address'], 16)
    d = workspace(addr, model)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    os.makedirs(os.path.dirname(result_path(addr, model)), exist_ok=True)
    shutil.copytree(os.path.join(ROOT, 'include'), os.path.join(d, 'include'), ignore=shutil.ignore_patterns('ref'))
    os.makedirs(os.path.join(d, 'docs'))
    shutil.copy(os.path.join(ROOT, 'docs', 'matching-notes.md'), os.path.join(d, 'docs'))
    text = open(os.path.join(ROOT, file), newline='').read()
    s, e = search.find_body(text, entry['symbol'])
    blank = text[:s] + '\n        // TODO (benchmark): write this function so that it compiles to CD2\'s code\n    ' + text[e:]
    dst = os.path.join(d, file)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, 'w', newline='').write(blank)
    name, scope = search.demangle_name(entry['symbol'])
    check_cmd = 'py -I %s bench check %s --model %s' % (_arg(os.path.join(ROOT, 'tools', 'cd2.py')), entry['address'],
                                                       model_dir(model))
    task = ['# Benchmark task %s' % entry['address'], '',
            'Write the body of `%s%s` in `%s` so that it compiles to exactly the code Crackdown 2 has at %s (%d bytes, '
            'tier %d).' % (scope + '::' if scope else '', name, file, entry['address'], entry['size'], brief['tier']), '',
            'Work only in this directory, and only from what is here: do not look for the solution anywhere else (the '
            'repository, the web). Edit headers in `include/` only if the function cannot be written otherwise.', '',
            'Check your work with this command, exactly as written (each run counts as an attempt):', '',
            '    ' + check_cmd, '',
            'It reports EXACT, or how many of the instruction words match. Read `docs/matching-notes.md` for the '
            'compiler\'s habits. No inline assembly, `__emit`, pragmas or pointer arithmetic (a cast to `char *` plus '
            'an offset, a pointer turned into an integer, a hard-coded address): the check rejects them. Use members '
            'and globals by name; declare a missing member in its class\'s header at its offset.', '',
            '## Hints', ''] + ['- ' + h for h in brief.get('hints', [])] + (['- none'] if not brief.get('hints') else []) + [
            '', '## Crackdown 2\'s code', '', '```', brief.get('assembly') or '(not available)', '```', '']
    open(os.path.join(d, 'TASK.md'), 'w', newline='\n').write('\n'.join(task))
    json.dump(dict(address=entry['address'], size=entry['size'], file=file, symbol=entry['symbol'], tier=brief['tier'],
                   model=model, prepared=datetime.datetime.now().isoformat(timespec='seconds'), attempts=0, exact=False,
                   check=check_cmd, blank_sha=file_sha(dst)),
              open(result_path(addr, model), 'w'), indent=1)
    return d


def file_sha(path):
    import hashlib
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def agent_failed(res, ws_file=None):
    """The agent exited with an error and did nothing: it ran no check and left the workspace's file as prepared.
    Such a task says nothing about the model (a usage limit, a missing key, a crash) and is not scored. A timeout, or
    an error exit after some work, is a genuine attempt."""
    code = res.get('agent_exit')
    if isinstance(code, bool) or not isinstance(code, int) or code == 0 or res.get('attempts', 0):
        return False
    if ws_file and os.path.exists(ws_file):
        if res.get('blank_sha'):
            return file_sha(ws_file) == res['blank_sha']
        # recorded before the prepared file's hash was: the blanked body's marker is still there if nothing was written
        return 'TODO (benchmark)' in open(ws_file, errors='replace').read()
    return True  # no workspace left to look at


def agent_log_tail(addr, model, n=600):
    """The end of the agent's output, without terminal colour codes."""
    p = os.path.join(workspace(addr, model), 'agent.log')
    text = open(p, errors='replace').read() if os.path.exists(p) else ''
    return re.sub(r'\x1b\[[0-9;]*m', '', text).strip()[-n:]


def mark_agent_error(addr, model):
    """Record the task as an agent error (not scored), with the end of the agent's output as the detail."""
    rp = result_path(addr, model)
    res = json.load(open(rp))
    res.update(status='agent error', exact=False, agent_error=True, words=0, detail=agent_log_tail(addr, model))
    json.dump(res, open(rp, 'w'), indent=1)
    return res


def mark_scored(addr, model):
    """Record that the task's result counts (the agent worked on it)."""
    rp = result_path(addr, model)
    res = json.load(open(rp))
    res['agent_error'] = False
    json.dump(res, open(rp, 'w'), indent=1)
    return res


def needs_run(addr, model):
    """For `bench run --resume`: true unless the task already has a genuine result (its agent finished, or timed out,
    and did not fail without working)."""
    rp = result_path(addr, model)
    if not os.path.exists(rp):
        return True
    res = json.load(open(rp))
    if 'agent_exit' not in res or res.get('agent_error'):
        return True
    return agent_failed(res, os.path.join(workspace(addr, model), res['file']))


def check(addr, model, read, known, aliases, count=True, policy=None):
    """Score the workspace's function: the source policy (policy(src, workspace) -> errors), then compile and compare.
    The verdict is this check's: a later failing check undoes an earlier EXACT. Updates and returns the result."""
    d = workspace(addr, model)
    rp = result_path(addr, model)
    res = json.load(open(rp))
    src = os.path.join(d, res['file'])
    # a fresh object file per check, deleted afterwards: no file is reused, so nothing still held by another process
    # (a virus scanner, the indexer) from an earlier check gets in the way
    fd, obj = tempfile.mkstemp(prefix='%08X_' % addr, suffix='.obj', dir=os.path.dirname(rp))
    os.close(fd)
    env = dict(os.environ, PATH=BIN + ';' + os.environ['PATH'],
               INCLUDE=os.path.join(XDK, 'include', 'xbox') + ';' + os.path.join(d, 'include'))
    res['attempts'] += bool(count)
    res['last_check'] = datetime.datetime.now().isoformat(timespec='seconds')
    res['exact'] = False
    target = read(addr, res['size'])
    errors = policy(src, d) if policy and os.path.exists(src) else []
    r = None
    if not os.path.exists(src):
        res.update(status='missing', words=0, of=len(target) // 4, detail='%s was deleted' % res['file'])
    elif errors:
        res.update(status='rejected by the source policy', words=0, of=len(target) // 4, detail='; '.join(errors)[:1500])
    else:
        r = run_compiler([os.path.join(BIN, 'cl.exe')] + FLAGS + ['/I' + os.path.dirname(src), '/Fo' + obj, src], env=env)
    if r is None:
        pass
    elif r.returncode:
        res.update(status='compile error', words=0, of=len(target) // 4, detail=(r.stdout + r.stderr)[-1500:])
    else:
        found = [(n, c, rl) for n, c, rl in coff.functions(obj) if res['symbol'] in n]
        if not found:
            res.update(status='missing', words=0, of=len(target) // 4, detail='no compiled function matches %s' % res['symbol'])
        else:
            name, code, rl = found[0]
            exact, ratio = coff.compare(code, target, rl)
            total = max(len(code), len(target)) // 4
            problems = []
            if exact:
                robj = relocs.Obj(obj)
                rs, problems = relocs.resolve(robj, name, target, addr)
                problems += relocs.check_consistency([(res['file'], name, s, a, k, o, robj) for s, a, k, o in rs],
                                                     read, aliases, dict(known, **{name: addr}))
            res.update(status='EXACT' if exact and not problems else 'WRONG TARGET' if exact else '%d/%d words' % (round(ratio * total), total),
                       words=round(ratio * total), of=total, detail='; '.join(problems))
            res['exact'] = exact and not problems
            if res['exact'] and count and 'solved_at_attempt' not in res:
                res['solved_at_attempt'] = res['attempts']
    if os.path.exists(src):
        ours = body_text(open(src, newline='').read(), res['symbol'])
        orig = body_text(open(os.path.join(ROOT, res['file']), newline='').read(), res['symbol'])
        res['same_as_repository'] = bool(ours) and ours == orig
    try:
        os.remove(obj)
    except OSError:
        pass
    json.dump(res, open(rp, 'w'), indent=1)
    return res


def run_agent(addr, model, agent, timeout, changes=None):
    """Run the agent command in the workspace. changes: environment variables to set for it (None: remove).
    Returns (exit code or 'timeout', seconds)."""
    d = workspace(addr, model)
    rp = result_path(addr, model)
    res = json.load(open(rp))
    task = os.path.join(d, 'TASK.md')
    env = dict(os.environ, CD2_TASK=task, CD2_WORKSPACE=d, CD2_CHECK=res['check'])
    for k, v in (changes or {}).items():
        if v is None:
            env.pop(k, None)
        else:
            env[k] = v
    cmd = agent.replace('{task}', '"%s"' % task).replace('{workspace}', '"%s"' % d)
    t0 = time.time()
    try:
        with open(task) as stdin, open(os.path.join(d, 'agent.log'), 'w') as log:
            r = subprocess.run(cmd, shell=True, cwd=d, env=env, stdin=stdin, stdout=log, stderr=subprocess.STDOUT,
                               timeout=timeout)
        code = r.returncode
    except subprocess.TimeoutExpired:
        code = 'timeout'
    secs = round(time.time() - t0, 1)
    res = json.load(open(rp))  # the agent may have run checks meanwhile
    res.update(agent=agent, agent_exit=code, agent_seconds=secs)
    json.dump(res, open(rp, 'w'), indent=1)
    return code, secs


# ---------------------------------------------------------------------------------------------------- self-test agents
# Run by `cd2.py bench selftest` as agents, in the workspace (CD2_WORKSPACE). Only the oracle may reach EXACT.

def _task_file(d):
    """(path of the workspace's source file, the repository-relative file, the symbol), from TASK.md and the workspace."""
    task = open(os.path.join(d, 'TASK.md')).read()
    file = re.search(r'in `([^`]+\.cpp)` so that', task).group(1)
    res = json.load(open(result_path(int(os.path.basename(d), 16), os.path.basename(os.path.dirname(d)))))
    return os.path.join(d, file), file, res['symbol']


def oracle(d):
    """Paste the repository's known solution into the workspace."""
    path, file, symbol = _task_file(d)
    orig = open(os.path.join(ROOT, file), newline='').read()
    s, e = search.find_body(orig, symbol)
    w = open(path, newline='').read()
    s2, e2 = search.find_body(w, symbol)
    open(path, 'w', newline='').write(w[:s2] + orig[s:e] + w[e2:])


def cheat_emit(d):
    """Emit CD2's own instruction words (listed in TASK.md) as the body."""
    path, file, symbol = _task_file(d)
    words = re.findall(r'/\* [0-9A-F]{8} [0-9A-F]{8}  ([0-9A-F]{2}) ([0-9A-F]{2}) ([0-9A-F]{2}) ([0-9A-F]{2}) \*/',
                       open(os.path.join(d, 'TASK.md')).read())
    w = open(path, newline='').read()
    s, e = search.find_body(w, symbol)
    body = ''.join('\n        __emit 0x%s;' % ''.join(x) for x in words)
    open(path, 'w', newline='').write(w[:s] + body + '\n    ' + w[e:])


def cheat_include(d):
    """Compile the repository's own file instead of the workspace's."""
    path, file, symbol = _task_file(d)
    open(path, 'w').write('#include "%s"\n' % os.path.join(ROOT, file).replace('\\', '/'))


def cheat_result(d):
    """Forge the results: claim EXACT in a result file, inside the workspace and beside it, and do no work."""
    forged = dict(exact=True, status='EXACT', attempts=1, solved_at_attempt=1)
    json.dump(forged, open(os.path.join(d, 'result.json'), 'w'))
    path = result_path(int(os.path.basename(d), 16), os.path.basename(os.path.dirname(d)))
    res = json.load(open(path))
    res.update(forged)
    json.dump(res, open(path, 'w'))


SELFTEST_AGENTS = {'oracle': oracle, 'cheat-emit': cheat_emit, 'cheat-include': cheat_include,
                   'cheat-result': cheat_result}


def mock_chat_server():
    """A local OpenAI-compatible chat API standing in for a model (the self-test of tools/bench_chat.py). Its first
    reply tries to read the harness's result file outside the workspace; only when that is refused does it answer
    with the repository's solution. Returns (server, base URL); stop it with server.shutdown()."""
    import http.server, threading

    class Handler(http.server.BaseHTTPRequestHandler):
        def log_message(self, *args):
            pass

        def do_POST(self):
            req = json.loads(self.rfile.read(int(self.headers['Content-Length'])))
            msgs = req['messages']
            first = msgs[1]['content']
            addr = re.search(r'Benchmark task (0x[0-9A-F]{8})', first).group(1)
            file = re.search(r'in `([^`]+\.cpp)` so that', first).group(1)
            symbol = next(t['symbol'] for t in load_suite()['tasks'] if t['address'] == addr)
            if len(msgs) == 2:
                reply = 'READ ../results/%s.json' % addr[2:]
            elif 'refused' in msgs[-1]['content']:
                orig = open(os.path.join(ROOT, file), newline='').read()
                s, e = search.find_body(orig, symbol)
                reply = 'Here is the body:\n```cpp\n%s\n```' % orig[s:e].strip('\n')
            else:
                reply = '```cpp\nreturn;\n```'  # the escape was not refused: answer wrongly, so the self-test fails
            out = json.dumps(dict(id='mock', object='chat.completion', model=req['model'],
                                  choices=[dict(index=0, message=dict(role='assistant', content=reply),
                                                finish_reason='stop')],
                                  usage=dict(prompt_tokens=1, completion_tokens=1))).encode()
            self.send_response(200)
            self.send_header('Content-Type', 'application/json')
            self.send_header('Content-Length', str(len(out)))
            self.end_headers()
            self.wfile.write(out)

    class Server(http.server.ThreadingHTTPServer):
        request_queue_size = 128  # every self-test chat agent may connect at once; a refused one backs off for seconds

    server = Server(('127.0.0.1', 0), Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, 'http://127.0.0.1:%d/v1' % server.server_address[1]


def report(model=None):
    rows = []
    if os.path.isdir(BENCH):
        for m in sorted(os.listdir(BENCH)):
            if model and m != model_dir(model):
                continue
            rdir = os.path.join(BENCH, m, 'results')
            for t in sorted(os.listdir(rdir)) if os.path.isdir(rdir) else []:
                if t.endswith('.json'):
                    rows.append(json.load(open(os.path.join(rdir, t))))
    table = collections.defaultdict(lambda: dict(tasks=0, exact=0, attempts=0, seconds=0.0, same_as_repository=0,
                                                 agent_errors=0, not_run=0))
    for r in rows:
        failed = r['agent_error'] if 'agent_error' in r else agent_failed(
            r, os.path.join(workspace(int(r['address'], 16), r.get('model')), r['file']))
        ran = 'last_check' in r  # prepared but never checked: the run was stopped, or an IDE workspace not scored yet
        for k in ('%s / tier %d' % (r.get('model') or 'unnamed', r['tier']), '%s / all' % (r.get('model') or 'unnamed')):
            if failed:  # the agent never worked on it: not a result for the model
                table[k]['agent_errors'] += 1
                continue
            if not ran:
                table[k]['not_run'] += 1
                continue
            table[k]['tasks'] += 1
            table[k]['exact'] += bool(r['exact'])
            table[k]['attempts'] += r['attempts']
            table[k]['seconds'] += r.get('agent_seconds', 0.0)
            table[k]['same_as_repository'] += bool(r.get('same_as_repository'))
    return rows, dict(table)


